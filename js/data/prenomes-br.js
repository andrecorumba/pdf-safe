//        - each of the 5,571 municipalities, for all decades together and for the
//          decades 1960, 1970, 1980, 1990, 2000 and 2010.
//      (Queries that returned no data were skipped.) 1,789 distinct names.
//   2. The national count of each candidate, summed over all decades, was
//      fetched from /nomes/{name} (4 candidates without national data were dropped).
//   3. Cut-off: national count >= 2,000 occurrences in the 2010 Census.
//
//  Result: 1595 names. This is smaller than the ~2,000 the design
